// ---------------------------------------------------------------------------
// Authorship (Roadmap v2, Phase 13.1).
//
// Pages are attributed to the QuickBizCalc editorial team as an Organization,
// not to a named person. No invented people, no invented credentials: the
// site's authority comes from the primary sources each page links to (see
// src/lib/seo-data/sources.ts and /editorial-policy).
//
// When a real, credentialed reviewer agrees to appear on the site, add them
// here as `kind: 'person'` with their real name, credential and profile link,
// and point the paycheck pages' `reviewer` at them.
// ---------------------------------------------------------------------------
import { SITE_NAME, SITE_URL, CONTACT_EMAIL } from './registry/site';

export interface Author {
  slug: string;
  /** Organization = the editorial team; person = a real named individual */
  kind: 'organization' | 'person';
  name: string;
  /** Short role line shown in bylines */
  role: string;
  /** 2–4 sentences shown on the editorial policy page */
  bio: string;
  /** Site path the byline links to */
  path: string;
  /** Absolute URL to a square photo or logo */
  image?: string;
  /** Public profiles — rendered as links and as schema.org `sameAs` */
  links: { label: string; url: string }[];
  email?: string;
}

