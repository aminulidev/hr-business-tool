export type AuthorSlug = keyof typeof AUTHORS;

export const DEFAULT_AUTHOR_SLUG: AuthorSlug = 'editorial-team';

export function getAuthor(slug?: string): Author {
  return (slug && slug in AUTHORS ? AUTHORS[slug as AuthorSlug] : AUTHORS[DEFAULT_AUTHOR_SLUG]) as Author;
}

export function getAllAuthors(): Author[] {
  return Object.values(AUTHORS);
}

export function authorUrl(author: Author): string {
  return `${SITE_URL}${author.path}`;
}

/** schema.org node for JSON-LD `author` / `reviewedBy`: Organization for the team, Person for a named reviewer */
export function authorJsonLd(author: Author) {
  const sameAs = author.links.length ? { sameAs: author.links.map((l) => l.url) } : {};
  if (author.kind === 'organization') {
    return {
      '@type': 'Organization',
      name: author.name,
      url: authorUrl(author),
      ...(author.image ? { logo: { '@type': 'ImageObject', url: author.image } } : {}),
      ...sameAs,
    };
  }
  return {
    '@type': 'Person',
    name: author.name,
    url: authorUrl(author),
    jobTitle: author.role,
    ...(author.image ? { image: author.image } : {}),
    ...sameAs,
    worksFor: { '@type': 'Organization', name: SITE_NAME, url: SITE_URL },
  };
}

/** schema.org Organization node for JSON-LD `publisher` */
export function publisherJsonLd() {
  return {
    '@type': 'Organization',
    name: SITE_NAME,
    url: SITE_URL,
    logo: { '@type': 'ImageObject', url: `${SITE_URL}/logo.svg` },
  };
}

/** "November 6, 2026" from "2026-11-06"; falls back to the raw string */
export function formatReviewDate(iso: string): string {
  const d = new Date(`${iso}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });
}
